"""涂油判定的全部数值门限与常量。

这些参数原先散落在 ``pipeline.py`` 顶部，现在集中放在这里，便于现场标定
时一眼看全，也避免判定逻辑被一两百行注释淹没。

分组：

- 跟踪与采样节拍（帧间隔估计、采样周期标定帧率）；
- 「盘里的静置杆」判定窗口（丝杆位置历史、回看时长）；
- 取料：手部判据（进盘定性、carry 证据、握持）；
- 取料：丝杆离盘判据（记录寿命、出盘确认、杆的形状）；
- 人工二次涂油（同杆容差、拼接窗口、遮挡补时半径）；
- 二级判定（规则否决门限）。

时间类门限一律**按秒**，距离类按"画面对角线归一化"，与帧率无关。只有
``frame_scale`` 放大的那一小撮（见 docs/05 §5.0.3）才依赖帧间隔。
"""

from __future__ import annotations

# ----------------------------------------------------------------------
# 跟踪与采样节拍
# ----------------------------------------------------------------------

# 手/刷头的 track id 命名空间，方便日志与 UI 区分。
_HAND_ID_BASE = 100_000
_BRUSH_ID_BASE = 200_000

# 帧间隔鲁棒估计的样本数。单帧长间隔（视频跳帧、推理卡顿）不应该改变
# 距离门限，所以用中位数而不是「上一帧的间隔」。
_FRAME_GAP_WINDOW = 15

# 区外延续跟踪的硬上限（归一化），不随 frame_scale 放大。
_ROI_TRACK_LIMIT_ABS = 0.10

# 取料判定的采样周期标定帧率（fps）。
#
# ``pick_sample_every_frames`` 的原义是「每 k 帧采一个点」，那套参数是在
# 15fps 的示例录像上调出来的。判定一旦按帧数数点，帧率变了采样密度就变、
# 动作攒到的点数也变，同一段录像换个帧率会给出不同结论（实测把 122925
# 插帧到 20fps 后取料从 17 掉到 13）。所以现在把「k 帧」固定换算成
# ``k / 15`` 秒，采样只跟**时间**走，与运行时帧率、``max_fps`` 都无关。
_PICK_SAMPLE_CALIBRATION_FPS = 15.0


# ----------------------------------------------------------------------
# 「盘里的静置杆」判定
# ----------------------------------------------------------------------
#
# 盘内那排丝杆是**位置长期不动**的；被手带走的杆即使在中心还没离开盘区时，
# 框也已经在动。只按「杆心在不在盘区」排除静置杆会漏判：手工 tray_roi 覆盖
# 了盘体下方的手臂活动范围，取料瞬间手里那根杆的中心往往还落在盘区内
# （示例④ 第 2、3 次取料的整段离盘初期都是这样），于是被当成静置杆丢掉，
# 整件取料判不出来。
#
# 实测四段示例视频：静置杆与回看窗口前的位置 IoU 在 0.5 以上（p50 0.9+），
# 被带走的杆 0.3 以下；分界清晰，取 0.5。
#
# 对照窗口按**时间**取（0.533s = 标定帧率 15fps 下的 8 帧），不按帧数：
# 20fps 下数 8 帧只有 0.4s、15fps 下 0.53s，同一根杆在两个帧率下的
# 「动没动」判定会给出不同结论。
_SCREW_STATIC_BACK = 8
_SCREW_STATIC_LOOKBACK_S = _SCREW_STATIC_BACK / _PICK_SAMPLE_CALIBRATION_FPS
_SCREW_STATIC_IOU = 0.5
# 丝杆位置历史保留的时长。要比回看窗口长一点，保证真能取到那一帧的对照。
_SCREW_HISTORY_S = _SCREW_STATIC_LOOKBACK_S + 4.0 / _PICK_SAMPLE_CALIBRATION_FPS
# 兜底条数上限：2fps 之类极低帧率下若只按时长裁剪，条数不会失控（时长本身
# 已限制了它），这里只是防御性上限。
_SCREW_HISTORY_MAX = 256

# 「同一根杆」的判定距离（归一化）：位置没动过的杆只有在离锚点这么近时才
# 仍被当成锚点自己那根。盘里相邻丝杆间距 0.02~0.03，取 0.02 以内的重叠
# 不会把旁边的静置杆误认成锚点（见 ``_static_anchor_ok``）。
_ANCHOR_SAME_SCREW_DISTANCE = 0.02


# ----------------------------------------------------------------------
# 取料（一）：手部判据（空手进盘 → 带杆离盘）
# ----------------------------------------------------------------------

# 手已出盘、手里那根杆还没出盘时，最多等这么久（按实际帧率缩放）。
#
# 取料的定义是「带杆**出**盘」，杆心在盘区内的读数是无效的，既不能进采样
# 窗口，也不能用来结算。这段时间要按「杆出盘」算：现场实测杆心比手晚出门
# 一秒上下是常态，示例⑤ 第 2 次取料更是在盘区下沿一边刷一边把杆往下带，
# 手出盘 6.53s、杆出盘 8.73s，隔了 2.2s。而按离盘后的固定结算时长
# （0.4s）计时，示例⑤ 会在杆出盘之前就按空手定论、整件取料丢掉。
#
# 上限只作兜底：正常情况下「还握着并带着杆」这个条件本身会先消失（手离开
# 那根杆、或杆出了盘），不会真等满。示例① 第 88~103 帧那种盘边点按的
# 假动作，手一撤这条就断，几帧内就按空手结算。
_CARRY_OUT_OF_TRAY_MAX_S = 5.0

# 判断「这根杆是不是进盘时那批存货」的 IoU 门限。
_INVENTORY_SAME_IOU = 0.5

# carry 那根杆「确实被手带着走」的门限（见 :class:`_CarryEvidence`）。
#
# 光「手边有盘内的杆」不够：手框接近盘宽（实测 350×400 px），盘里的存货、
# 夹具上的杆都会落进来。真取料时杆要么持续落在手框里，要么跟着手动。
#
# 严格锁杆后实测（9 段示例视频，逐次进盘）：
#
#   真取料        落手达标帧数 3~33，或 杆/手 位移比 0.6~1.2
#   示例⑧ 装夹具  落手 0 帧，杆位移 0.000 / 手 0.028
#   示例⑨ 盘边划过 落手 0 帧，杆位移 0.001 / 手 0.061
#   示例① 点按夹具 落手 0 帧，杆/手 位移比 0.21
#
# 「落手面积 ≥0.30」的分档依据：盘边蹭到的静置杆 0.25~0.42、真攥住 ≥0.44
# （与 ``_GRIP_PARKED_MIN_FRAC`` 同一批实测），取 0.30 落在划过与攥住之间。
_CARRY_INHAND_MIN = 0.30
# 「落手面积达标的累计**时长**」门限（秒），与 ``_CARRY_INHAND_FRAMES``
# 等价：那是 15fps 下限 3 帧 = 0.2s。按帧数数会在高帧率下更容易满足
# （20fps 时 3 帧只有 0.15s），判定随帧率漂移；按秒算则与帧率无关。
_CARRY_INHAND_S = 0.20
# 同上，按帧计数的写法只为日志/诊断保留，判定不再用它。
_CARRY_INHAND_FRAMES = 3
_CARRY_ROD_MOVE_MIN = 0.010
_CARRY_ROD_FOLLOW_RATIO = 0.40
# 「杆持续落在手里」这一条还必须附带的**最低**位移证据：杆自身至少要动这么多，
# 且达到手位移的这个比例。
#
# 只有「面积落手 ≥0.30」不够。装料/整理料盘时，工人手伸进盘里、把杆放下，
# 手框（实测 350×400 px，比杆长）会大面积盖住**躺在盘里那根杆**，落手面积
# 能到 0.90、连续 7 帧达标——但杆自己几乎没动（实测 rod_move 0.002 /
# hand_move 0.027，比值 0.07）。这类动作按「落手面积」会被判成「带杆离盘」，
# 凭空多一件取料，还顶掉后面正在等涂油的周期、多报一次漏涂 NG
# （示例 091916 0.47s 即如此）。
#
# 真取料走这条分支时杆是跟着手走的，实测 rod_move/hand_move 在 0.49~1.21。
# 取 0.02（约为最小的真取料 0.017 的 1.2 倍以下）与 0.25 的比值门限，
# 落在「放杆 0.002/0.07」与「带走 0.017/0.49」之间。
_CARRY_INHAND_ROD_MOVE_MIN = 0.008
_CARRY_INHAND_FOLLOW_RATIO = 0.25

# 「杆跟着手动」还要求两者同向：位移向量夹角的余弦 ≥ 这个值（约 60°）。
# 夹具上的杆会随检测框抖动慢慢漂移，位移方向与手完全无关（示例⑨：手往
# 盘下沿走 +y，杆却在原地小幅晃动）。
_CARRY_FOLLOW_COS = 0.50
# 锁杆后单帧允许的位置跳变（归一化）。盘里相邻杆间距 0.02~0.03，取 0.05
# 既跟得住被带走时的手，又不会一步跳到旁边另一根上。
_CARRY_LOCK_STEP = 0.05

# 对**位置没动过**的杆，握持要求杆有足够面积落在手框右上区（实测盘边蹭到的
# 静置杆 0.25~0.42，真正攥住的 ≥0.44）；对已经在动的杆，只要与右上区相交
# 即算——它不可能是静置杆。
_GRIP_PARKED_MIN_FRAC = 0.50

# 「纯位置连续性」跟进手持丝杆的单帧位移上限（不随帧率放大）。
#
# 与「杆与本周期那只手交叠」的证据强度不同：握持是强证据，取料瞬间手带杆
# 快速划出，单帧位移可达 0.11；纯位置连续性只是「上一帧在这、这一帧还在
# 附近」，允许的跨度必须小得多，否则锚点会一步跳到旁边另一根杆上（实测
# 在 0.15 的跨度下会被另一只手的杆抢走）。
_CONTINUITY_STEP_ABS = 0.08

# 取料判据的来源标记，写进事件证据与周期，便于现场区分是哪条规则判出的。
_PICK_SOURCE_HAND = "hand_exit"
_PICK_SOURCE_SCREW_EXIT = "screw_exit"


# ----------------------------------------------------------------------
# 取料（二）：丝杆离盘判据
# ----------------------------------------------------------------------

# 丝杆离盘判据的接续与确认门限。
#
# 这条判据只看杆、不看手，所以杆的身份要靠**位置连续性**自己维护：同一根
# 杆相邻帧位移很小，换一根则跨度大得多。
# ``_SCREW_TRACK_MISS``：连续多少帧没再见到这根杆就丢弃它的出盘记录。
# 杆被手完全遮住几帧是常态，太短会把一次取料切成两段（跟踪器本身也有
# ``screw_exit_track_missing_s`` 兜着，这里只是一层额外的保险）。
_SCREW_TRACK_MISS = 8

# 一条**从没动过**的丝杆出盘记录最多活这么久（秒），超过就释放。
#
# 盘里那排杆从视频开头就在、一直不动。给每根都留着记录的话，记录会越积
# 越多（实测 122925 同时有 14 条），后来真的被取走的那根抢不到新记录，
# 「在盘里放稳过 → 出盘」这条流程就永远走不到。取 2.0s：足够让一根刚放进
# 盘里的杆把 ``screw_exit_pick_inside_s``（默认 0.3s）攒够，又不会长期占坑。
# 动过的记录不受这个限制（``_ScrewExit.active``）。
_SCREW_EXIT_IDLE_RELEASE_S = 2.0

# 「杆确实出盘了」的确认：连续看到它在盘外至少这么多帧、且持续这么久。
#
# 这两项**不随帧率放大**，和 ``pick_confirm_s`` 同类——它们的作用是滤掉
# 检测框抖动（杆框细长，倾斜时框心来回摆一两个百分点），不是判定门限。
# 按帧率放大会在低帧率下等到一秒以上才确认，视频结束前可能根本等不到。
_SCREW_EXIT_MIN_FRAMES = 2
_SCREW_EXIT_MIN_OUTSIDE_S = 0.20

# 建丝杆记录时要求框至少有多细长（长边/短边）。丝杆实测 p50≈4、p90 6~10；
# 盘区下沿被误检成 screw 的手/夹具/白方块是 1~1.3。取 2.0 落在中间。
_ROD_MIN_ASPECT = 2.0


# ----------------------------------------------------------------------
# 人工二次涂油
# ----------------------------------------------------------------------

# 「涂油还是同一根杆」的单帧位移容差（归一化，不随帧率放大）。
#
# 刷的时候手一直在动，杆框会随之晃动：实测同一根杆相邻帧的位置跳变在
# 0.03 以内，换一根杆则是 0.1 以上（盘里相邻杆间距 0.02~0.03，但工人
# 刷完一件换下一件要抬起来重新放，跨度远大于这个）。取 0.06 落在两者之间。
_OILING_SAME_ROD_STEP = 0.06

# 刷手抬开多久仍算同一次涂油（秒，按帧率放大）。
#
# 现场同一件料中途抬手的空档实测 0.5~1.3 s，不同料之间最短 1.07 s；
# 单靠时间分不开，所以这个上限只用来兜底「长时间不碰就该收段」，
# 真正的切分由杆的位置决定（见 ``_same_oiling_rod``）。
_OILING_STITCH_GAP_S = 1.6

# 涂油时「正在刷的那根杆这一帧算不算被检出」的判定半径（归一化）。
#
# 用于 ``_oiling_rod_occluded_contact``：拳头压住杆会让那根杆整帧漏检，
# 但盘里别的杆还在，所以要按锚点附近有没有杆框来区分「这根被遮住」与
# 「手已经松开」。取 0.055：实测同一根杆相邻帧的框心跳变 ≤0.03（见
# ``_OILING_SAME_ROD_STEP``），而盘内相邻杆间距 0.02~0.03、盘下方工作台
# 离盘区下沿远大于这个距离，不会把别处的杆算成这一根。
_OILING_ROD_OCCLUDED_RADIUS = 0.055


# ----------------------------------------------------------------------
# 二级判定（规则 + 模型融合）
# ----------------------------------------------------------------------

# 规则判「是」时，模型概率低于多少就改判「否」。
#
# 原先规则投真即定论、模型完全不参与，代价是「整理料盘」被判成取料
# （现场 2026-11-27 10:40：手在盘里挪杆 6.75 秒后空手离开，规则投真、
# 模型 p=0.146 强烈判否，仍报了取料 + 漏涂 NG）。
#
# 实测 25 次真取料（规则=True）概率全部 ≥ 0.653，4 次误判全部 ≤ 0.196。
# 取 0.40 落在两者中间偏误判一侧，离真取料下界还有 0.25 余量。
_RULE_TRUE_VETO_P = 0.40
